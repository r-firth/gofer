const GLYPHS = Object.fromEntries(
  Object.entries(FACE).map(([key, rows]) => [key, rows.split(" ")]),
);
const ROWS = 9;

export function Matrix({
  text,
  label,
  id,
}: {
  text: string;
  label?: string;
  id?: string;
}) {
  const grid: boolean[][] = Array.from({ length: ROWS }, () => []);
  [...text.toLowerCase()].forEach((char, index) => {
    const glyph = GLYPHS[char] ?? GLYPHS["-"];
    for (let row = 0; row < ROWS; row++) {
      if (index) grid[row].push(false);
      for (let col = 0; col < glyph[0].length; col++)
        grid[row].push(glyph[row]?.[col] === "#");
    }
  });
  const cols = grid[0].length;
  return (
    <div className="dm" id={id} role="img" aria-label={label ?? text}>
      <svg
        viewBox={`0 0 ${cols} ${ROWS}`}
        style={{ width: `calc(${cols} * var(--mx))` }}
        aria-hidden="true"
      >
        {grid.flatMap((row, r) =>
          row.map((on, c) => (
            <circle
              key={r * cols + c}
              className={on ? "on" : undefined}
              cx={c + 0.6}
              cy={r + 0.6}
              r={0.4}
            />
          )),
        )}
      </svg>
    </div>
  );
}
